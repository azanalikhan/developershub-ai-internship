"""
Scores zero-shot vs few-shot tagging predictions (models/predictions.csv,
generated by tagging.py) against ground-truth tags.

Usage:
    python evaluate.py
"""
import json
from pathlib import Path

import pandas as pd

MODELS_DIR = Path(__file__).parent / "models"
PREDICTIONS_PATH = MODELS_DIR / "predictions.csv"


def _split_tags(cell) -> set:
    if pd.isna(cell) or not str(cell).strip():
        return set()
    return {t.strip() for t in str(cell).split(";") if t.strip()}


def score_strategy(df: pd.DataFrame, pred_col: str) -> dict:
    precisions, recalls, top1_hits = [], [], []

    for _, row in df.iterrows():
        true_tags = _split_tags(row["true_tags"])
        pred_tags_ordered = [t.strip() for t in str(row[pred_col]).split(";") if t.strip()]
        pred_tags = set(pred_tags_ordered)

        if pred_tags:
            precision = len(pred_tags & true_tags) / len(pred_tags)
        else:
            precision = 0.0
        recall = len(pred_tags & true_tags) / len(true_tags) if true_tags else 0.0

        top1 = pred_tags_ordered[0] if pred_tags_ordered else None
        top1_hit = 1.0 if top1 and top1 in true_tags else 0.0

        precisions.append(precision)
        recalls.append(recall)
        top1_hits.append(top1_hit)

    n = len(df)
    return {
        "avg_precision_at_3": sum(precisions) / n,
        "avg_recall": sum(recalls) / n,
        "top1_match_rate": sum(top1_hits) / n,
    }


def main():
    if not PREDICTIONS_PATH.exists():
        raise FileNotFoundError(
            f"{PREDICTIONS_PATH} not found. Run `python tagging.py` first to generate predictions."
        )

    df = pd.read_csv(PREDICTIONS_PATH)

    zero_shot_metrics = score_strategy(df, "zero_shot_tags")
    few_shot_metrics = score_strategy(df, "few_shot_tags")

    print("=== Zero-shot vs Few-shot comparison ===\n")
    print(f"{'Metric':<22} {'Zero-shot':>12} {'Few-shot':>12}")
    for key in zero_shot_metrics:
        print(f"{key:<22} {zero_shot_metrics[key]:>12.3f} {few_shot_metrics[key]:>12.3f}")

    out = {"zero_shot": zero_shot_metrics, "few_shot": few_shot_metrics}
    with open(MODELS_DIR / "comparison_metrics.json", "w") as f:
        json.dump(out, f, indent=2)
    print(f"\nSaved comparison metrics to {MODELS_DIR / 'comparison_metrics.json'}")


if __name__ == "__main__":
    main()
